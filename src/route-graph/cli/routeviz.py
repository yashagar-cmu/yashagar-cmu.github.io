def route_json(r):
    keep = ("family", "dest", "gateway", "flags", "iface", "expire", "raw", "extra", "os", "ok",
            "cidr", "plen", "scope", "bits", "gw", "kind", "tags", "node")
    d = {k: r.get(k) for k in keep if k in r}
    if r.get("ok"):
        d["flags_explained"] = explain_flags(r)
    return d


def payload(nodes, routes, meta, hostname, source, lookups=()):
    return {
        "hostname": hostname, "source": source, "generated": dt.datetime.now().strftime("%Y-%m-%d %H:%M"),
        "os": meta.get("os"), "hide_default": list(HIDE_DEFAULT),
        "columns": COLUMNS, "routes": [route_json(r) for r in routes], "nodes": nodes,
        "glossary": flag_glossary(routes), "lookups": list(lookups),
    }


