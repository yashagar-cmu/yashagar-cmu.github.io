# --------------------------------------------------------------------------- cli

def run(cmd):
    try:
        return subprocess.run(cmd, capture_output=True, text=True, check=True).stdout
    except (OSError, subprocess.CalledProcessError) as e:
        sys.exit("could not run %s: %s" % (" ".join(cmd), e))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter,
                                 epilog=__doc__.split("\n", 2)[2])
    ap.add_argument("input", nargs="?", help="file with `netstat -rn` output ('-' = stdin; default: stdin if piped, else --live)")
    ap.add_argument("-f", "--format", choices=("html", "svg", "text", "dot", "json"), default="html")
    ap.add_argument("-o", "--output", help="output file (html defaults to routes.html; other formats to stdout)")
    ap.add_argument("--live", action="store_true", help="run `netstat -rn` (and ifconfig) on this machine")
    ap.add_argument("--ifconfig", metavar="FILE", help="ifconfig -a / ip addr output to label interfaces with")
    ap.add_argument("--hostname", help="name for the host node")
    ap.add_argument("--to", action="append", default=[], metavar="ADDR",
                    help="explain the longest-prefix match for ADDR and highlight it (repeatable)")
    ap.add_argument("--all", action="store_true", help="text/svg/dot: include multicast and bookkeeping routes")
    ap.add_argument("--hide", default=",".join(HIDE_DEFAULT),
                    help="text/svg/dot: comma list of multicast,bookkeeping,linklocal,loopback,neighbors,reject")
    ap.add_argument("--open", action="store_true", help="open the html output in the browser")
    a = ap.parse_args(argv)

    ifcfg_text, source = "", ""
    if a.input and a.input != "-":
        text = pathlib.Path(a.input).read_text(encoding="utf-8", errors="replace")
        source = "from %s" % a.input
    elif a.input == "-" or (not a.live and not sys.stdin.isatty()):
        text = sys.stdin.read()
        source = "from stdin"
    else:
        a.live = True
        text = run(["netstat", "-rn"])
        source = "netstat -rn on %s" % socket.gethostname()
        if sys.platform == "darwin":
            ifcfg_text = run(["ifconfig", "-a"])
        elif sys.platform.startswith("linux"):
            try:
                ifcfg_text = subprocess.run(["ip", "addr"], capture_output=True, text=True, check=True).stdout
            except (OSError, subprocess.CalledProcessError):
                ifcfg_text = ""
    if a.ifconfig:
        ifcfg_text = pathlib.Path(a.ifconfig).read_text(encoding="utf-8", errors="replace")
    hostname = a.hostname or (socket.gethostname() if a.live else "this host")

    try:
        routes, meta = parse_netstat(text)
    except ParseError as e:
        sys.exit("routeviz: %s" % e)
    classify(routes)
    ifcfg = parse_ifconfig(ifcfg_text) if ifcfg_text else {}
    nodes = build_graph(routes, ifcfg, hostname, source)

    lookups, highlight = [], []
    for addr in a.to:
        try:
            res = lookup(routes, addr)
        except ValueError:
            sys.exit("routeviz: not an IP address: %s" % addr)
        lookups.append({"addr": res["addr"], "node": res["winner"]["node"] if res["winner"] else None,
                        "text": explain_lookup(res, nodes)})
        if res["winner"]:
            highlight.extend(path_to_root(nodes, res["winner"]["node"]))
        if a.format != "json":
            print(explain_lookup(res, nodes), file=sys.stderr if a.format != "text" else sys.stdout)
            if a.format == "text":
                print()

    hide = () if a.all else tuple(h for h in a.hide.split(",") if h)
    vis = visible_set(nodes, hide)
    if a.format == "html":
        out = render_html(payload(nodes, routes, meta, hostname, source, lookups))
    elif a.format == "svg":
        out = render_svg(nodes, routes, vis, highlight)
    elif a.format == "text":
        out = render_text(nodes, routes, vis, highlight)
    elif a.format == "dot":
        out = render_dot(nodes, routes, vis)
    else:
        out = json.dumps(payload(nodes, routes, meta, hostname, source, lookups), indent=1, ensure_ascii=False)

    if a.format == "html" and a.output != "-":
        path = pathlib.Path(a.output or "routes.html")
        path.write_text(out, encoding="utf-8")
        n4 = sum(1 for r in routes if r.get("ok") and r["family"] == 4)
        n6 = sum(1 for r in routes if r.get("ok") and r["family"] == 6)
        print("wrote %s (%d IPv4 + %d IPv6 routes, %d nodes)" % (path, n4, n6, len(nodes)), file=sys.stderr)
        if a.open:
            opener = {"darwin": "open", "win32": "start"}.get(sys.platform, "xdg-open")
            subprocess.call([opener, str(path)])
    elif a.output and a.output != "-":
        pathlib.Path(a.output).write_text(out + "\n", encoding="utf-8")
    else:
        sys.stdout.write(out + "\n")


if __name__ == "__main__":
    main()
