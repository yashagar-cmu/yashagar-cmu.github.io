#!/usr/bin/env python3
"""routeviz: draw a routing table (``netstat -rn`` output) as a graph.

Input is any ``netstat -rn`` text: macOS/BSD (``Destination Gateway Flags Netif``),
Linux (``Kernel IP routing table`` with Genmask, ``Kernel IPv6 routing table``)
or Windows (``Network Destination Netmask Gateway Interface Metric``). Nothing is
tied to this machine; ``--live`` merely runs ``netstat -rn`` for you.

    python3 src/route-graph/cli/routeviz.py routes.txt                # -> routes.html
    netstat -rn | python3 src/route-graph/cli/routeviz.py -o out.html
    python3 src/route-graph/cli/routeviz.py --live --open             # this machine, open in browser
    python3 src/route-graph/cli/routeviz.py routes.txt -f text        # tree in the terminal
    python3 src/route-graph/cli/routeviz.py routes.txt --to 8.8.8.8   # longest-prefix match
    python3 src/route-graph/cli/routeviz.py routes.txt -f dot | dot -Tpng -o routes.png

The graph is a tree read left to right, the way a packet leaves the host:

    host -> interface -> connected prefix -> next hop / neighbor -> remote prefix

* An interface owns the prefixes it is directly attached to (no ``G`` flag).
* Hosts on those links (ARP/NDP cache entries, ``H`` routes) hang under the
  prefix that contains them; a next-hop router is such a neighbor too.
* Routes with the ``G`` flag hang under the router that forwards them; the
  default route (``/0``) is the shortest prefix and catches everything else.

Outputs: ``html`` (interactive page, default), ``svg`` (static), ``text`` (tree),
``dot`` (Graphviz), ``json`` (the graph model). Stdlib only, Python 3.9+.
"""

