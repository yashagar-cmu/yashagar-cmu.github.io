def render_svg(nodes, routes, vis, highlight=()):
    hl = set(highlight)
    pos, W, H, cols = layout(nodes, vis)
    out = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">' % (W, H, W, H),
           "<style>%s</style>" % SVG_CSS, '<rect width="100%" height="100%" fill="#fcfcfb"/>']
    for (x, w), (_, title) in zip(cols, COLUMNS):
        out.append('<text class="col" x="%d" y="18">%s</text>' % (x, html.escape(title.upper())))
    for nid in vis:
        n = nodes[nid]
        for c in n["children"]:
            if c not in vis:
                continue
            x1, y1, w1, h1 = pos[nid]
            x2, y2, w2, h2 = pos[c]
            ax, ay, bx, by = x1 + w1, y1 + h1 / 2, x2, y2 + h2 / 2
            mx = (ax + bx) / 2
            k = nodes[c]
            cls = "edge" + (" default" if k["kind"] == "default" else "") \
                + (" dashed" if "reject" in k["tags"] or "unresolved" in k["tags"] else "") \
                + (" hl" if nid in hl and c in hl else "")
            out.append('<path class="%s" d="M%.1f %.1f C%.1f %.1f %.1f %.1f %.1f %.1f"/>' % (cls, ax, ay, mx, ay, mx, by, bx, by))
    for nid in vis:
        n = nodes[nid]
        x, y, w, h = pos[nid]
        cls = n["kind"] + (" dim" if "reject" in n["tags"] or "unresolved" in n["tags"] else "") + (" hl" if nid in hl else "")
        out.append('<g class="%s"><title>%s</title><rect x="%.1f" y="%.1f" width="%d" height="%d"/>' % (
            cls, html.escape(node_tooltip(n, routes)), x, y, w, h))
        if n["sub"]:
            out.append('<text x="%.1f" y="%.1f">%s</text><text class="sub" x="%.1f" y="%.1f">%s</text>' % (
                x + 9, y + 15, html.escape(n["label"]), x + 9, y + 30, html.escape(n["sub"][:48])))
        else:
            out.append('<text x="%.1f" y="%.1f">%s</text>' % (x + 9, y + 17, html.escape(n["label"])))
        out.append("</g>")
    out.append("</svg>")
    return "\n".join(out)


def node_tooltip(n, routes):
    lines = [n["label"] + (" - " + n["sub"] if n["sub"] else "")]
    if n["note"]:
        lines.append(n["note"])
    for i in n["routes"]:
        r = routes[i]
        lines.append(r["raw"].strip())
        lines.extend("  " + f for f in explain_flags(r))
    return "\n".join(lines)


